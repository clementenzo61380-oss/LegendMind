open(f"{BASE}/database.py", "w").write(
'import aiosqlite\n'
'import time\n'
'import os\n'
'from dotenv import load_dotenv\n'
'load_dotenv()\n'
'DB_PATH = os.getenv("DB_PATH", "data/bot.db")\n'
'\n'
'async def init_db():\n'
'    async with aiosqlite.connect(DB_PATH) as db:\n'
'        await db.executescript("""\n'
'            CREATE TABLE IF NOT EXISTS cache (\n'
'                cache_key TEXT PRIMARY KEY,\n'
'                value TEXT,\n'
'                source TEXT,\n'
'                created INTEGER\n'
'            );\n'
'            CREATE TABLE IF NOT EXISTS logs (\n'
'                id INTEGER PRIMARY KEY AUTOINCREMENT,\n'
'                guild_id TEXT,\n'
'                user_id TEXT,\n'
'                command TEXT,\n'
'                result TEXT,\n'
'                ai_used TEXT,\n'
'                cost REAL,\n'
'                created INTEGER\n'
'            );\n'
'            CREATE TABLE IF NOT EXISTS blacklist (\n'
'                user_id TEXT PRIMARY KEY,\n'
'                reason TEXT,\n'
'                created INTEGER\n'
'            );\n'
'            CREATE TABLE IF NOT EXISTS rate_limit (\n'
'                user_id TEXT PRIMARY KEY,\n'
'                count INTEGER,\n'
'                window_start INTEGER\n'
'            );\n'
'            CREATE TABLE IF NOT EXISTS feedback (\n'
'                id INTEGER PRIMARY KEY AUTOINCREMENT,\n'
'                user_id TEXT,\n'
'                link TEXT,\n'
'                note INTEGER,\n'
'                created INTEGER\n'
'            );\n'
'        """)\n'
'        await db.commit()\n'
'\n'
'async def get_cache(key):\n'
'    try:\n'
'        async with aiosqlite.connect(DB_PATH) as db:\n'
'            async with db.execute("SELECT value, created FROM cache WHERE cache_key=?", (key,)) as c:\n'
'                row = await c.fetchone()\n'
'                if row and (time.time() - row[1]) < 86400:\n'
'                    return row[0]\n'
'                if row:\n'
'                    await db.execute("DELETE FROM cache WHERE cache_key=?", (key,))\n'
'                    await db.commit()\n'
'    except Exception:\n'
'        pass\n'
'    return None\n'
'\n'
'async def set_cache(key, value, source="", hours=24):\n'
'    try:\n'
'        async with aiosqlite.connect(DB_PATH) as db:\n'
'            await db.execute(\n'
'                "INSERT OR REPLACE INTO cache (cache_key, value, source, created) VALUES (?,?,?,?)",\n'
'                (key, value, source, int(time.time()))\n'
'            )\n'
'            await db.commit()\n'
'    except Exception:\n'
'        pass\n'
'\n'
'async def is_blacklisted(user_id):\n'
'    try:\n'
'        async with aiosqlite.connect(DB_PATH) as db:\n'
'            async with db.execute("SELECT 1 FROM blacklist WHERE user_id=?", (user_id,)) as c:\n'
'                return await c.fetchone() is not None\n'
'    except Exception:\n'
'        return False\n'
'\n'
'async def check_rate_limit(user_id, limit=10, window=3600):\n'
'    try:\n'
'        now = int(time.time())\n'
'        async with aiosqlite.connect(DB_PATH) as db:\n'
'            async with db.execute("SELECT count, window_start FROM rate_limit WHERE user_id=?", (user_id,)) as c:\n'
'                row = await c.fetchone()\n'
'            if row:\n'
'                count, start = row\n'
'                if now - start > window:\n'
'                    await db.execute("UPDATE rate_limit SET count=1, window_start=? WHERE user_id=?", (now, user_id))\n'
'                elif count >= limit:\n'
'                    await db.commit()\n'
'                    return False\n'
'                else:\n'
'                    await db.execute("UPDATE rate_limit SET count=count+1 WHERE user_id=?", (user_id,))\n'
'            else:\n'
'                await db.execute("INSERT INTO rate_limit (user_id, count, window_start) VALUES (?,1,?)", (user_id, now))\n'
'            await db.commit()\n'
'        return True\n'
'    except Exception:\n'
'        return True\n'
'\n'
'async def log_command(guild_id, user_id, command, result, ai_used="", cost=0.0):\n'
'    try:\n'
'        async with aiosqlite.connect(DB_PATH) as db:\n'
'            await db.execute(\n'
'                "INSERT INTO logs (guild_id, user_id, command, result, ai_used, cost, created) VALUES (?,?,?,?,?,?,?)",\n'
'                (str(guild_id), str(user_id), command, result, ai_used, cost, int(time.time()))\n'
'            )\n'
'            await db.commit()\n'
'    except Exception:\n'
'        pass\n'
)
print("OK: database.py")

