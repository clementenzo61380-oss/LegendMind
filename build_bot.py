open(f"{BASE}/youtube_search.py", "w").write(
'import os\n'
'import requests\n'
'from dotenv import load_dotenv\n'
'load_dotenv()\n'
'YT_KEY = os.getenv("YOUTUBE_API_KEY", "")\n'
'\n'
'def search_youtube_coc(query, max_results=3):\n'
'    if not YT_KEY:\n'
'        return []\n'
'    try:\n'
'        r = requests.get(\n'
'            "https://www.googleapis.com/youtube/v3/search",\n'
'            params={"part": "snippet", "q": query + " Clash of Clans 2025",\n'
'                    "type": "video", "maxResults": max_results, "key": YT_KEY},\n'
'            timeout=5\n'
'        )\n'
'        results = []\n'
'        for item in r.json().get("items", []):\n'
'            results.append({\n'
'                "title": item["snippet"]["title"],\n'
'                "url": "https://youtu.be/" + item["id"]["videoId"],\n'
'                "description": item["snippet"]["description"][:400],\n'
'                "channel": item["snippet"]["channelTitle"]\n'
'            })\n'
'        return results\n'
'    except Exception as e:\n'
'        print("[YouTube]", e)\n'
'        return []\n'
'\n'
'def youtube_context(videos):\n'
'    if not videos:\n'
'        return ""\n'
'    lines = ["Informations issues de vraies videos Clash of Clans sur YouTube :"]\n'
'    for v in videos:\n'
'        lines.append("- " + v["title"] + " (" + v["channel"] + ") : " + v["description"])\n'
'    return "\\n".join(lines)\n'
)
