open(f"{BASE}/ai_cascade.py", "w").write(
'from __future__ import annotations\n'
'import os, asyncio\n'
'from typing import Optional, Tuple\n'
'from dotenv import load_dotenv\n'
'load_dotenv()\n'
'\n'
'GROQ_KEY = os.getenv("GROQ_API_KEY", "")\n'
'GEMINI_KEY = os.getenv("GEMINI_API_KEY", "")\n'
'ANTHROPIC_KEY = os.getenv("ANTHROPIC_API_KEY", "")\n'
'\n'
'COC_SYSTEM = (\n'
'    "Tu es ClashBot, expert Clash of Clans. "\n'
'    "Reponds UNIQUEMENT avec de vraies troupes, heros et batiments officiels du jeu. "\n'
'    "Troupes reelles : Barbare, Archer, Geant, Gobelin, Briseur de mur, Ballon, Sorcier, "\n'
'    "Guerisseuse, Dragon, PEKKA, Mini PEKKA, Golem, Valkyrie, Golem de lave, Witch, Bowler, "\n'
'    "Mineurs, Electro Dragon, Yeti, Dragon de glace, Super troupes. "\n'
'    "Heros officiels : Roi Barbare, Reine des Archers, Grand Faucon, Marionnettiste Royal, Champion. "\n'
'    "N invente AUCUN nom. HDV max actuel : 18. Reponds en francais, simplement et avec fun."\n'
')\n'
'\n'
'async def ask_groq(prompt: str) -> Tuple[Optional[str], str, float]:\n'
'    if not GROQ_KEY:\n'
'        return None, "groq", 0.0\n'
'    try:\n'
'        from groq import Groq\n'
'        client = Groq(api_key=GROQ_KEY)\n'
'        r = await asyncio.to_thread(lambda: client.chat.completions.create(\n'
'            messages=[{"role": "user", "content": COC_SYSTEM + "\\n\\n" + prompt}],\n'
'            model="llama-3.3-70b-versatile", max_tokens=1500))\n'
'        text = r.choices[0].message.content\n'
'        if text and len(text.strip()) > 20:\n'
'            return text.strip(), "groq-llama3", 0.0\n'
'    except Exception as e:\n'
'        print("[Groq]", e)\n'
'    return None, "groq", 0.0\n'
'\n'
'async def ask_gemini(prompt: str) -> Tuple[Optional[str], str, float]:\n'
'    if not GEMINI_KEY:\n'
'        return None, "gemini", 0.0\n'
'    try:\n'
'        from google import genai\n'
'        client = genai.Client(api_key=GEMINI_KEY)\n'
'        r = await asyncio.to_thread(lambda: client.models.generate_content(\n'
'            model="gemini-1.5-flash",\n'
'            contents=COC_SYSTEM + "\\n\\n" + prompt))\n'
'        text = r.text\n'
'        if text and len(text.strip()) > 20:\n'
'            return text.strip(), "gemini-1.5-flash", 0.0001\n'
'    except Exception as e:\n'
'        print("[Gemini]", e)\n'
'    return None, "gemini", 0.0\n'
'\n'
'async def ask_ai(prompt: str) -> Tuple[str, str, float]:\n'
'    for fn in [ask_groq, ask_gemini]:\n'
'        result, model, cost = await fn(prompt)\n'
'        if result:\n'
'            return result, model, cost\n'
'    return "Les IAs sont indisponibles. Reessaie dans quelques secondes !", "none", 0.0\n'
)
print("OK: ai_cascade.py")

