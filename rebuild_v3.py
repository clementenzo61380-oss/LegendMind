'    try:\n'
'        async with aiosqlite.connect(DB_PATH) as db:\n'
'            async with db.execute("SELECT 1 FROM blacklist WHERE user_id=?",(user_id,)) as c:\n'
'                return await c.fetchone() is not None\n'
'    except Exception:\n'
