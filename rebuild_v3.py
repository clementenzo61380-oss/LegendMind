'    try:\n'
'        now = int(time.time())\n'
'        async with aiosqlite.connect(DB_PATH) as db:\n'
'            async with db.execute("SELECT count,window_start FROM rate_limit WHERE user_id=?",(user_id,)) as c:\n'
