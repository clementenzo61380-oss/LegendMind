'                    await db.commit()\n'
'                    return False\n'
'                else:\n'
'                    await db.execute("UPDATE rate_limit SET count=count+1 WHERE user_id=?",(user_id,))\n'
'            else:\n'
'                await db.execute("INSERT INTO rate_limit(user_id,count,window_start) VALUES(?,1,?)",(user_id,now))\n'
