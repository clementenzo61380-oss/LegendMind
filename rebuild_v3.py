# vision.py — Roboflow → Gemini Vision
# ══════════════════════════════════════════
open(f"{BASE}/vision.py", "w").write(
'import os, asyncio, base64, json, re\n'
'import requests as req\n'
'from dotenv import load_dotenv\n'
'load_dotenv()\n'
'GEMINI_KEY = os.getenv("GEMINI_API_KEY","")\n'
'ROBOFLOW_KEY = os.getenv("ROBOFLOW_API_KEY","")\n'
'\n'
'async def detect_with_roboflow(image_url):\n'
'    if not ROBOFLOW_KEY:\n'
'        return None\n'
'    try:\n'
'        r = req.post(\n'
'            "https://detect.roboflow.com/clash-of-clans-vop4y/4",\n'
'            params={"api_key":ROBOFLOW_KEY,"image":image_url},\n'
'            timeout=10\n'
'        )\n'
'        data = r.json()\n'
'        predictions = data.get("predictions",[])\n'
'        if predictions:\n'
'            best = max(predictions, key=lambda x: x.get("confidence",0))\n'
'            confidence = best.get("confidence",0)*100\n'
'            label = best.get("class","").lower()\n'
'            hdv_match = re.search(r"th(\\d{1,2})", label)\n'
'            hdv = int(hdv_match.group(1)) if hdv_match else 0\n'
'            return {"hdv":hdv,"confidence":confidence,"label":label,"source":"roboflow"}\n'
'    except Exception as e:\n'
'        print("[Roboflow]",e)\n'
'    return None\n'
'\n'
'async def detect_with_gemini(image_url, prompt_extra=""):\n'
'    if not GEMINI_KEY:\n'
'        return None\n'
'    try:\n'
'        img_data = req.get(image_url, timeout=10).content\n'
'        content_type = "image/png"\n'
'        from google import genai\n'
'        from google.genai import types\n'
'        client = genai.Client(api_key=GEMINI_KEY)\n'
'        prompt = (\n'
'            "Tu es un expert Clash of Clans. Analyse ce screenshot.\\n"\n'
'            + prompt_extra\n'
'            + "Reponds UNIQUEMENT en JSON valide sans markdown :\\n"\n'
'            + \'{"hdv":X,"type_base":"diamond|box|ring|anti3|hybrid",\'\n'
'            + \'"style":"anti_air|anti_ground|anti_3stars|anti_2stars|farming",\'\n'
'            + \'"description":"description courte",\'\n'
'            + \'"points_forts":"forces de la base",\'\n'
'            + \'"points_faibles":"faiblesses de la base",\'\n'
'            + \'"confidence":X}\'\n'
'        )\n'
'        response = await asyncio.to_thread(lambda: client.models.generate_content(\n'
'            model="gemini-1.5-flash",\n'
'            contents=[\n'
'                types.Part.from_bytes(data=img_data, mime_type=content_type),\n'
'                types.Part.from_text(text=prompt)\n'
'            ]\n'
'        ))\n'
'        text = response.text.strip()\n'
'        match = re.search(r"\\{.*\\}", text, re.DOTALL)\n'
'        if match:\n'
'            return json.loads(match.group())\n'
'    except Exception as e:\n'
'        print("[GeminiVision]",e)\n'
'    return None\n'
'\n'
'async def analyze_base_image(image_url):\n'
'    default = {"hdv":0,"type_base":"unknown","style":"unknown","description":"Analyse impossible","points_forts":"","points_faibles":"","confidence":0}\n'
'    # 1. Roboflow en premier\n'
'    robo = await detect_with_roboflow(image_url)\n'
'    if robo and robo.get("confidence",0) >= 80:\n'
'        # Confiance suffisante avec Roboflow\n'
'        result = default.copy()\n'
'        result.update({"hdv":robo["hdv"],"confidence":robo["confidence"],"source":"roboflow"})\n'
'        # Enrichir avec Gemini pour les details\n'
'        gemini = await detect_with_gemini(image_url, "Roboflow a detecte TH"+str(robo["hdv"])+". Confirme et donne les details. ")\n'
'        if gemini:\n'
'            result.update(gemini)\n'
'        return result\n'
'    # 2. Gemini Vision si Roboflow insuffisant\n'
'    gemini = await detect_with_gemini(image_url)\n'
'    if gemini:\n'
'        return gemini\n'
'    return default\n'
'\n'
'async def analyze_attack_image(image_url):\n'
'    default = {"compo":"inconnue","etoiles":0,"pourcentage":0,"erreurs":[],"points_positifs":[],"note":5,"description":"Analyse impossible"}\n'
'    if not GEMINI_KEY:\n'
'        return default\n'
'    try:\n'
'        img_data = req.get(image_url, timeout=10).content\n'
'        from google import genai\n'
'        from google.genai import types\n'
'        client = genai.Client(api_key=GEMINI_KEY)\n'
'        prompt = (\n'
'            "Analyse ce replay d attaque Clash of Clans.\\n"\n'
'            + "Reponds UNIQUEMENT en JSON valide :\\n"\n'
'            + \'{"compo":"composition detectee","etoiles":X,"pourcentage":X,\'\n'
'            + \'"erreurs":["erreur1","erreur2"],"points_positifs":["point1"],\'\n'
'            + \'"note":X,"description":"description de l attaque"}\'\n'
'        )\n'
'        response = await asyncio.to_thread(lambda: client.models.generate_content(\n'
'            model="gemini-1.5-flash",\n'
'            contents=[\n'
'                types.Part.from_bytes(data=img_data, mime_type="image/png"),\n'
'                types.Part.from_text(text=prompt)\n'
'            ]\n'
'        ))\n'
'        import re, json\n'
'        match = re.search(r"\\{.*\\}", response.text.strip(), re.DOTALL)\n'
'        if match:\n'
'            return json.loads(match.group())\n'
'    except Exception as e:\n'
'        print("[VisionAttack]",e)\n'
'    return default\n'
)
